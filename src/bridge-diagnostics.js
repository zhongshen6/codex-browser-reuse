/*
 * Shared, bounded error summaries for the browser and backend.
 * Never serialize RPC data, request bodies, stacks, or arbitrary error fields.
 * The browser uses the same redaction rules before sending telemetry.
 */
((root, factory) => {
  const api = factory();
  if (typeof module === "object" && module.exports) module.exports = api;
  else root.__codexBridgeDiagnostics = api;
})(typeof window === "object" ? window : globalThis, () => {
  function redact(value, limit = 600) {
    // Redact before truncating so a long credential cannot lose its key prefix.
    return String(value ?? "")
      .replace(/https?:\/\/[^\s"'<>]+/gi, value => {
        try {
          const url = new URL(value);
          return `${url.protocol}//${url.hostname}${url.port ? `:${url.port}` : ""}/[redacted-path]`;
        } catch { return "[redacted-url]"; }
      })
      .replace(/\b(?:Bearer|Basic)\s+[A-Za-z0-9+/_.=-]+/gi, "[redacted-auth]")
      .replace(/\b(?:sk-[A-Za-z0-9_-]+|eyJ[A-Za-z0-9_-]+\.[A-Za-z0-9_-]+\.[A-Za-z0-9_-]+)\b/g,
        "[redacted-token]")
      .replace(/((?:password|passwd|secret|token|api[_-]?key|authorization|cookie|credential)\s*["']?\s*[:=]\s*)(?:"[^"]*"|'[^']*'|[^\s,;]+)/gi,
        "$1[redacted]")
      .replace(/[A-Z]:[\\/][^\r\n"'<>]*/gi, "[redacted-path]")
      .replace(/\\\\[^\\\s]+\\[^\r\n"'<>]*/g, "[redacted-path]")
      .replace(/(^|[\s"'(])\/(?:home|Users|root|tmp|mnt|var)\/[^\s"'<>]*/g, "$1[redacted-path]")
      .replace(/\b[A-Z0-9._%+-]+@[A-Z0-9.-]+\.[A-Z]{2,}\b/gi, "[redacted-email]")
      .replace(/[\r\n\t]+/g, " ")
      .slice(0, limit);
  }

  function summarize(error) {
    if (error == null) return undefined;
    // HTTP host errors may wrap the original JSON-RPC error; keep only its code.
    const upstream = error.rpcError;
    const code = upstream?.code ?? error.code;
    return {
      ...(typeof code === "number" || typeof code === "string"
        ? { code: typeof code === "number" ? code : redact(code, 80) } : {}),
      message: redact(typeof error === "string" ? error : error.message ?? error.error ?? "Request failed")
    };
  }

  function traceId(value) {
    // IDs are generated by the transport, not copied from URLs or user payloads.
    return typeof value === "string" && /^[a-zA-Z0-9-]{1,96}$/.test(value) ? value : undefined;
  }

  return { redact, summarize, traceId };
});
